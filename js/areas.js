/* Liga cada palavra das etapas a uma posição na lista geral (window.WORDS).
   Palavras que já existem (mesma grafia) são reaproveitadas; as novas entram no fim. */
(function () {
  const W = window.WORDS;
  const pos = new Map(W.map((w, i) => [w[0], i]));
  window.ETAPAS.forEach((e) => {
    if (e.kind !== "words") return;
    e.idx = e.words.map((w) => {
      const en = typeof w === "string" ? w : w[0];
      if (pos.has(en)) return pos.get(en);
      if (typeof w === "string") throw new Error("Palavra sem tradução: " + w);
      W.push(w);
      pos.set(en, W.length - 1);
      return W.length - 1;
    });
  });
})();
